package com.secureops.app.ml.benchmark

import android.content.ContentValues
import android.content.Context
import android.os.Build
import android.os.Environment
import android.provider.MediaStore
import com.google.gson.GsonBuilder
import com.secureops.app.data.local.entity.BenchmarkResultEntity
import timber.log.Timber
import java.io.File
import java.io.FileOutputStream
import java.io.OutputStream
import java.text.SimpleDateFormat
import java.util.Date
import java.util.Locale

/**
 * BenchmarkReportGenerator
 *
 * Exports benchmark results to:
 * - JSON (Downloads directory)
 * - PDF-like plain-text report (Downloads directory, using a structured txt format
 *   since Android has no built-in PDF API without 3rd-party libs)
 */
class BenchmarkReportGenerator(private val context: Context) {

    private val gson = GsonBuilder().setPrettyPrinting().create()
    private val dateFormat = SimpleDateFormat("yyyy-MM-dd HH:mm:ss", Locale.getDefault())
    private val fileStamp = SimpleDateFormat("yyyyMMdd_HHmmss", Locale.getDefault())

    // ----- JSON ---------------------------------------------------------------

    fun exportJson(result: BenchmarkResultEntity): String {
        val data = mapOf(
            "timestamp"       to dateFormat.format(Date(result.timestamp)),
            "inferenceTimeMs" to result.inferenceTimeMs,
            "memoryUsageMb"   to result.memoryUsageMb,
            "startupTimeMs"   to result.startupTimeMs,
            "precision"       to result.precision,
            "recall"          to result.recall,
            "f1Score"         to result.f1Score,
            "accuracy"        to result.accuracy,
            "productionReady" to isProductionReady(result)
        )
        val json = gson.toJson(data)
        val fileName = "secureops_benchmark_${fileStamp.format(Date())}.json"
        writeToDisk(fileName, json.toByteArray(), "application/json")
        Timber.i("JSON report exported: $fileName")
        return fileName
    }

    // ----- PDF (text-based) ---------------------------------------------------

    fun exportPdf(result: BenchmarkResultEntity): String {
        val report = buildReportText(result)
        val fileName = "secureops_benchmark_${fileStamp.format(Date())}.txt"
        writeToDisk(fileName, report.toByteArray(), "text/plain")
        Timber.i("Text report exported: $fileName")
        return fileName
    }

    // ----- helpers ------------------------------------------------------------

    private fun buildReportText(r: BenchmarkResultEntity): String = buildString {
        appendLine("=".repeat(60))
        appendLine("  SecureOps — ML Benchmark Report")
        appendLine("=".repeat(60))
        appendLine()
        appendLine("Date         : ${dateFormat.format(Date(r.timestamp))}")
        appendLine()
        appendLine("── Performance Metrics ────────────────────────────────────")
        appendLine("  Inference Time  : ${r.inferenceTimeMs} ms")
        appendLine("  Memory Delta    : ${"%.2f".format(r.memoryUsageMb)} MB")
        appendLine("  Startup Time    : ${r.startupTimeMs} ms")
        appendLine()
        appendLine("── ML Validation Metrics ──────────────────────────────────")
        appendLine("  Accuracy        : ${"%.2f".format(r.accuracy * 100)} %")
        appendLine("  Precision       : ${"%.2f".format(r.precision * 100)} %  [threshold ≥ 85%]")
        appendLine("  Recall          : ${"%.2f".format(r.recall * 100)} %  [threshold ≥ 80%]")
        appendLine("  F1 Score        : ${"%.4f".format(r.f1Score)}         [threshold ≥ 0.82]")
        appendLine()
        appendLine("── Production Readiness ───────────────────────────────────")
        appendLine("  Precision ≥ 85% : ${if (r.precision >= 0.85) "✅ PASS" else "❌ FAIL"}")
        appendLine("  Recall    ≥ 80% : ${if (r.recall    >= 0.80) "✅ PASS" else "❌ FAIL"}")
        appendLine("  F1        ≥ 0.82: ${if (r.f1Score   >= 0.82) "✅ PASS" else "❌ FAIL"}")
        appendLine()
        val ready = isProductionReady(r)
        appendLine("  Overall Status  : ${if (ready) "🎉 PRODUCTION READY" else "⚠️  NOT PRODUCTION READY"}")
        appendLine()
        appendLine("=".repeat(60))
        appendLine("  Generated by SecureOps v1.0 — github.com/secureops")
        appendLine("=".repeat(60))
    }

    private fun isProductionReady(r: BenchmarkResultEntity) =
        r.precision >= 0.85 && r.recall >= 0.80 && r.f1Score >= 0.82

    private fun writeToDisk(fileName: String, bytes: ByteArray, mimeType: String) {
        try {
            if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.Q) {
                val resolver = context.contentResolver
                val values = ContentValues().apply {
                    put(MediaStore.Downloads.DISPLAY_NAME, fileName)
                    put(MediaStore.Downloads.MIME_TYPE, mimeType)
                    put(MediaStore.Downloads.IS_PENDING, 1)
                }
                val uri = resolver.insert(MediaStore.Downloads.EXTERNAL_CONTENT_URI, values)
                    ?: throw Exception("MediaStore insert returned null")
                resolver.openOutputStream(uri)?.use { it.write(bytes) }
                values.clear()
                values.put(MediaStore.Downloads.IS_PENDING, 0)
                resolver.update(uri, values, null, null)
            } else {
                @Suppress("DEPRECATION")
                val dir = Environment.getExternalStoragePublicDirectory(Environment.DIRECTORY_DOWNLOADS)
                dir.mkdirs()
                File(dir, fileName).writeBytes(bytes)
            }
        } catch (e: Exception) {
            Timber.e(e, "Failed to write report to Downloads")
            // Fallback: write to app-private files dir
            File(context.filesDir, fileName).writeBytes(bytes)
        }
    }
}
